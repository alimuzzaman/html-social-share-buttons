#!/usr/bin/env node
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const anchor = /(^|[\s>+~])a(?=[\s.:#[,>+~]|$)/g;

// Copy only anchor rules, preserving conditional blocks and the old stylesheets.
function buttonRules(css) {
	css = css.replace(/\r\n?/g, '\n').replace(/\/\*[\s\S]*?\*\//g, '').replace(/@charset[^;]+;/g, '');
	let output = '', position = 0;
	while (position < css.length) {
		const open = css.indexOf('{', position);
		if (open < 0) break;
		let close = open + 1, depth = 1;
		for (; close < css.length && depth; close++) {
			if (css[close] === '{') depth++;
			if (css[close] === '}') depth--;
		}
		const selector = css.slice(position, open).trim();
		const body = css.slice(open + 1, close - 1);
		if (selector.startsWith('@media') || selector.startsWith('@supports')) {
			const nested = buttonRules(body);
			if (nested) output += selector + '{' + nested + '}\n';
		} else {
			const selectors = selector.split(',').filter((item) => /(^|[\s>+~])a(?=[\s.:#[,>+~]|$)/.test(item));
			if (selectors.length) output += selectors.map((item) => item.trim().replace(anchor, '$1button.hssb-native-button')).join(',') + '{' + body + '}\n';
		}
		position = close;
	}
	return output;
}

const files = ['iconset/default/style.css', 'iconset/flat/style.css', 'iconset/long_shadow/style.css', 'iconset/prajin/style.css', 'assets/iconsets/bootstrap-solid/style.css', 'assets/iconsets/tabler-outline/style.css', 'assets/frontend/button-appearance.css'];
const css = '/* Generated by scripts/generate-native-share-css.js; loaded only for Native share. */\n' +
	'.zmshbt button.hssb-native-button{padding:0;border:0;border-radius:0;background-color:transparent;cursor:pointer}\n' +
	files.map((file) => buttonRules(fs.readFileSync(path.join(root, file), 'utf8'))).join('\n');
const target = path.join(root, 'assets/frontend/native-share.css');
if (process.argv.includes('--check')) {
	if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== css) throw new Error('Native share CSS is stale.');
} else {
	fs.writeFileSync(target, css);
}
console.log('Native share CSS verified.');
